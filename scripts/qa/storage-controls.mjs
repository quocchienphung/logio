import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';

const base = process.argv[2] || 'http://localhost:3000';
const out = 'docs/research/storage/buttons/local';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const checks = [], errors = [];
const check = (label, value) => { assert.ok(value, label); checks.push(label); };
const rectInside = (rect, viewport) => rect && rect.x >= -1 && rect.y >= -1 && rect.x + rect.width <= viewport.width + 1 && rect.y + rect.height <= viewport.height + 1;
try {
 const context = await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
 const page = await context.newPage(); page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/personalize?section=storage`,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Skip',exact:true}).click();
 const trigger=page.getByRole('button',{name:'More upload actions'});
 await trigger.focus(); await page.keyboard.press('ArrowDown');
 const menu=page.getByRole('menu',{name:'Upload actions'});
 await menu.waitFor({state:'visible'});
 check('Split menu ArrowDown opens and focuses first enabled item',await page.getByRole('menuitem',{name:'Upload documents',exact:true}).evaluate(e=>e===document.activeElement));
 check('Desktop menu stays inside viewport',rectInside(await menu.boundingBox(),page.viewportSize()));
 await page.keyboard.press('ArrowDown');
 check('Menu keyboard skips disabled export',await page.getByRole('menuitem',{name:'Write a knowledge note'}).evaluate(e=>e===document.activeElement));
 await page.keyboard.press('End');
 check('Menu End selects last enabled item',await page.getByRole('menuitem',{name:'Write a knowledge note'}).evaluate(e=>e===document.activeElement));
 await page.keyboard.press('Escape');
 await menu.waitFor({state:'hidden'});
 check('Menu Escape restores trigger focus',await trigger.evaluate(e=>e===document.activeElement));
 await trigger.click(); await page.getByRole('menuitem',{name:'Write a knowledge note'}).click();
 check('Split alternative performs its action and dismisses popover',await page.getByRole('dialog',{name:'Write a knowledge note'}).isVisible() && !(await menu.isVisible()));
 await page.getByRole('button',{name:'Close write a knowledge note'}).click();
 const source='# Revenue knowledge\nAnnual finance revenue has grown. Banking provisions and SQL data are reviewed monthly.\n';
 const fixtures=[{name:'controls-finance.md',mimeType:'text/markdown',buffer:Buffer.from(source)},{name:'controls-sql.sql',mimeType:'text/plain',buffer:Buffer.from('SELECT account_id, SUM(revenue) FROM finance GROUP BY account_id;\n')}];
 await page.getByLabel('Choose storage documents').setInputFiles(fixtures);
 await page.getByRole('button',{name:'Process files',exact:true}).click();
 await page.getByText('Your review, before storage',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Approve & store',exact:true}).click();
 await page.locator('.stg-document-row').first().waitFor();
 await page.waitForFunction(()=>document.querySelectorAll('.stg-document-row').length===2);
 check('Async action processes and stores actual documents',await page.locator('.stg-document-row').count()===2);
 const filters=page.getByRole('group',{name:'Filter documents by knowledge area'});
 await filters.getByRole('button',{name:/^Banking/}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.stg-document-row').length===0);
 check('Filter group updates actual results',await page.locator('.stg-document-row').count()===0);
 await filters.getByRole('button',{name:/^All/}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.stg-document-row').length===2);
 const row=page.locator('.stg-document-row').filter({hasText:'controls-finance.md'});
 const actions=row.getByRole('group',{name:'Actions for controls-finance.md'});
 await actions.scrollIntoViewIfNeeded();
 const downloadAction=actions.getByRole('button',{name:'Download',exact:true});
 const before=await downloadAction.boundingBox();
 await downloadAction.hover(); await page.waitForTimeout(550);
 check('Expanding row action grows on hover',(await downloadAction.boundingBox()).width>before.width+30);
 await actions.screenshot({path:`${out}/expanding-hover-1440.png`});
 await row.getByRole('checkbox',{name:'Select controls-finance.md'}).check();
 const toolbar=page.getByRole('toolbar',{name:'Selected document actions'});
 await toolbar.getByRole('button',{name:'Download ZIP'}).focus(); await page.keyboard.press('ArrowRight');
 check('Selected floating toolbar supports arrow navigation',await toolbar.getByRole('button',{name:'Delete',exact:true}).evaluate(e=>e===document.activeElement));
 await toolbar.screenshot({path:`${out}/floating-selected-1440.png`});
 await toolbar.getByRole('button',{name:'Clear',exact:true}).click();
 check('Floating Clear changes real selection',!(await toolbar.isVisible()));
 await row.locator('.stg-file-name button').click();
 const detail=page.getByRole('dialog',{name:'controls-finance.md',exact:true});
 await detail.getByRole('button',{name:'Copy fingerprint',exact:true}).click();
 const fingerprint=await page.evaluate(()=>navigator.clipboard.readText());
 check('Copy button writes exact actual SHA-256',fingerprint===createHash('sha256').update(source).digest('hex'));
 await detail.getByRole('button',{name:'Copy text',exact:true}).click();
 check('Copy text writes actual extracted content',(await page.evaluate(()=>navigator.clipboard.readText())).includes('Annual finance revenue'));
 await detail.screenshot({path:`${out}/copy-detail-1440.png`});
 await detail.getByRole('button',{name:'Delete document',exact:true}).click();
 await page.keyboard.press('Escape');
 check('Confirm Escape cancels inline confirmation and keeps detail modal',await detail.isVisible() && await detail.getByRole('button',{name:'Delete document',exact:true}).isVisible());
 await detail.getByRole('button',{name:'Delete document',exact:true}).click();
 await detail.getByRole('button',{name:'Cancel',exact:true}).click();
 check('Confirm Cancel preserves the document',await page.locator('.stg-document-row').count()===2);
 await detail.getByRole('button',{name:'Delete document',exact:true}).click();
 await page.waitForTimeout(400);
 await detail.screenshot({path:`${out}/confirm-1440.png`});
 await detail.getByRole('button',{name:'Delete',exact:true}).click();
 await detail.waitFor({state:'hidden'});
 await page.waitForFunction(()=>document.querySelectorAll('.stg-document-row').length===1);
 check('Confirmation commits deletion of the selected original',await page.locator('.stg-document-row').count()===1);
 const desktopGeometry=await page.locator('.stg-split,.stg-split-trigger,.stg-expanding-group,.stg-floating-group,.stg-copy').evaluateAll(elements=>elements.map(e=>({class:e.className,rect:JSON.stringify(e.getBoundingClientRect()),font:getComputedStyle(e).font,radius:getComputedStyle(e).borderRadius,padding:getComputedStyle(e).padding})));
 await page.setViewportSize({width:390,height:844});
 await trigger.scrollIntoViewIfNeeded(); await trigger.click();
 await menu.waitFor({state:'visible'});
 check('Phone menu stays inside viewport',rectInside(await menu.boundingBox(),page.viewportSize()));
 await page.waitForTimeout(350);
 await page.screenshot({path:`${out}/split-menu-390.png`});
 await page.keyboard.press('Escape');
 await page.getByRole('checkbox',{name:'Select controls-sql.sql'}).check();
 await page.waitForTimeout(350);
 check('Phone floating toolbar stays inside viewport',rectInside(await toolbar.boundingBox(),page.viewportSize()));
 await page.screenshot({path:`${out}/selected-390.png`});
 const geometry=await page.locator('.stg-split,.stg-split-trigger,.stg-expanding-group,.stg-floating-group,.stg-copy').evaluateAll(elements=>elements.map(e=>({class:e.className,rect:JSON.stringify(e.getBoundingClientRect()),font:getComputedStyle(e).font,radius:getComputedStyle(e).borderRadius,padding:getComputedStyle(e).padding})));
 await fs.writeFile(`${out}/measurements.json`,JSON.stringify({desktop:desktopGeometry,phone:geometry},null,2));
 await page.setViewportSize({width:1440,height:1000});
 await toolbar.getByRole('button',{name:'Clear',exact:true}).click();
 await page.locator('.ui-as-user').click();
 await page.getByRole('menuitem',{name:'Dark mode',exact:true}).click();
 await page.locator('.stg-page-head h1').click();
 check('Real account preference enables dark controls',await page.locator('.crm-page').getAttribute('data-theme')==='dark');
 await trigger.scrollIntoViewIfNeeded(); await trigger.click(); await page.waitForTimeout(350);
 const darkMenu=await menu.evaluate(e=>({background:getComputedStyle(e).backgroundColor,color:getComputedStyle(e).color}));
 check('Native popover inherits dark surface and light text',darkMenu.background!=='rgb(255, 255, 255)' && darkMenu.color!=='rgb(23, 23, 23)');
 await page.screenshot({path:`${out}/split-menu-1440-dark.png`});
 await page.keyboard.press('Escape');
 const finalRow=page.locator('.stg-document-row').filter({hasText:'controls-sql.sql'});
 await finalRow.locator('.stg-file-name button').click();
 const darkDetail=page.getByRole('dialog',{name:'controls-sql.sql',exact:true});
 const darkCopy=darkDetail.getByRole('button',{name:'Copy fingerprint',exact:true});
 await darkCopy.click(); await page.waitForTimeout(700);
 const iconColors=await darkCopy.evaluate(e=>({button:getComputedStyle(e).color,stroke:getComputedStyle(e.querySelector('svg path:last-child')).stroke,opacity:getComputedStyle(e.querySelector('svg path:last-child')).opacity,width:getComputedStyle(e.querySelector('svg')).strokeWidth}));
 check('Copied icon retains visible currentColor stroke in dark mode',iconColors.stroke===iconColors.button && +iconColors.opacity>.8 && iconColors.width==='1.75px');
 await darkDetail.getByRole('button',{name:'Delete document',exact:true}).click();
 await page.waitForTimeout(400);
 await darkDetail.screenshot({path:`${out}/confirm-copy-1440-dark.png`});
 await fs.writeFile(`${out}/dark-colors.json`,JSON.stringify({menu:darkMenu,copy:iconColors},null,2));
 check('No browser runtime errors',errors.length===0);
 await fs.writeFile(`${out}/results.json`,JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({passed:checks.length,checks,errors},null,2));
} finally {await browser.close();}

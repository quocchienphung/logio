import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const out='docs/research/uiarc-skilled/interactions';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome'});
const checks=[],errors=[];
const check=(name,condition)=>{assert.ok(condition,name);checks.push(name);};
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://localhost:3000/skilled',{waitUntil:'networkidle'});
  const target=page.getByRole('button',{name:/^Skill target:/});
  const source=page.getByRole('button',{name:/^Skill source:/});
  check('Target and metric use custom menus, with no native select',await page.locator('.sk-workspace select').count()===0);
  await target.focus();await page.keyboard.press('Enter');
  await page.getByRole('menuitemradio',{name:'Local AI',exact:true}).waitFor();
  check('Current target is announced as checked',await page.getByRole('menuitemradio',{name:'Local AI',exact:true}).getAttribute('aria-checked')==='true');
  await page.keyboard.press('End');await page.keyboard.press('Enter');
  await page.getByRole('menu').waitFor({state:'hidden'});
  check('Keyboard selection changes target and closes menu',await target.getAttribute('aria-label')==='Skill target: AI Agent');
  check('Selection restores trigger focus',await target.evaluate(e=>e===document.activeElement));
  await target.click();await page.waitForTimeout(260);
  await page.screenshot({path:`${out}/local-target-menu.png`});
  const geometry=await page.getByRole('menu').evaluate(e=>{const s=getComputedStyle(e);return{radius:s.borderRadius,font:s.font,width:e.getBoundingClientRect().width};});
  check('Menu uses the observed 16px popup radius',geometry.radius==='16px');
  await page.keyboard.press('Escape');await page.getByRole('menu').waitFor({state:'hidden'});
  check('Escape closes without changing target',await target.getAttribute('aria-label')==='Skill target: AI Agent');
  await target.click();await page.getByLabel('Skill instructions',{exact:true}).click();await page.getByRole('menu').waitFor({state:'hidden'});
  check('Click outside closes menu',true);
  await source.click();await page.waitForTimeout(260);await page.screenshot({path:`${out}/local-source-menu.png`});
  await page.getByRole('menuitem',{name:'GitHub repository',exact:true}).click();
  const url=page.getByLabel('GitHub repository or skill URL',{exact:false});
  await url.waitFor();await page.getByRole('menu').waitFor({state:'hidden'});
  check('GitHub action focuses the URL field',await url.evaluate(e=>e===document.activeElement));
  await url.fill('https://example.com/not-github');await page.getByRole('button',{name:'Add skill',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Only public HTTPS'}).waitFor();
  check('Invalid URL error is beside the composer',await page.locator('.sk-composer-error').isVisible());
  check('Local validation does not fabricate failed network measurements',await page.locator('.sk-metrics strong').first().innerText()==='0');
  await url.fill('https://github.com/anthropics/skills');await page.getByRole('button',{name:'Add skill',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Choose a skill',exact:true});await picker.waitFor({timeout:30000});
  check('Repository URL discovers choices instead of failing',await picker.getByRole('button',{name:'Import skill',exact:true}).count()>1);
  await picker.getByLabel('Search discovered skills').fill('webapp-testing');
  check('Discovered skills can be searched',await picker.getByRole('button',{name:'Import skill',exact:true}).count()===1);
  await page.screenshot({path:`${out}/local-discovered-skills.png`});
  await picker.getByRole('button',{name:'Import skill',exact:true}).click();
  const card=page.locator('.sk-card').filter({has:page.getByRole('button',{name:'webapp-testing',exact:true})});await card.waitFor({timeout:30000});
  check('Chosen repository skill imports into the selected target',(await card.locator('.sk-card-meta').innerText()).includes('AI Agent'));
  const toggle=card.getByRole('button',{name:'webapp-testing',exact:true});
  check('Imported card starts expanded',await toggle.getAttribute('aria-expanded')==='true');
  await page.waitForTimeout(350);await page.screenshot({path:`${out}/local-expanded-card.png`});
  await toggle.click();await page.waitForTimeout(400);
  check('Collapsed details stay mounted and inert',await card.locator('.sk-card-details').evaluate(e=>e.inert&&e.querySelector('pre')!==null));
  await toggle.click();await page.waitForTimeout(400);
  check('Reopening restores captured content',await card.getByRole('heading',{name:/Supporting files/}).isVisible());
  const metric=page.getByRole('button',{name:/^Measurement type:/});await metric.click();await page.waitForTimeout(260);await page.screenshot({path:`${out}/local-metric-menu.png`});
  await page.getByRole('menuitemradio',{name:'Imports',exact:true}).click();await page.getByRole('menu').waitFor({state:'hidden'});
  check('Metric picker selection changes its value',await metric.getAttribute('aria-label')==='Measurement type: Imports');
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(350);await target.scrollIntoViewIfNeeded();await target.click();await page.waitForTimeout(260);
  const bounds=await page.getByRole('menu').boundingBox();
  check('Mobile popup stays inside viewport',bounds.x>=0&&bounds.x+bounds.width<=390);
  check('Mobile page has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:`${out}/local-mobile-menu.png`});await page.keyboard.press('Escape');
  await page.setViewportSize({width:320,height:844});await page.waitForTimeout(350);
  check('Small 320px layout fits without horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('Interaction workflow has no runtime errors',errors.length===0);
  console.log(`${checks.length} interaction checks passed.`);
  await context.close();
}finally{await fs.writeFile(`${out}/qa-results.json`,JSON.stringify({checks,errors},null,2));await browser.close();}

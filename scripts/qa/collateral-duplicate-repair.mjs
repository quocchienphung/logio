import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from 'playwright';
import { buildXlsx } from '../../src/components/sites/collateral/excel-formation/engine/xlsx-builder.mjs';
import { readWorkbook } from '../../src/components/sites/collateral/excel-formation/engine/xlsx-reader.ts';
const base = process.argv[2] ?? 'http://localhost:3000', out = 'docs/auto-repair/duplicate-browser';
await fs.mkdir(out, { recursive: true });
const headers = ['MACNTCTD', 'MAKH', 'MASOBD', 'MALOAIBD', 'GIATRI', 'MOTABDS', 'MOTABD'];
const row = asset => ['001', '002', asset, '303', { n: '1234.5599999999999' }, 'May moc thi?t bi 3', 'May moc thi?t bi 3'];
const input = buildXlsx([{ name: 'Synthetic', rows: [headers, row('A'), row('A'), row('A'), row('B')], hiddenRows: [3] }]);
const browser = await chromium.launch({ channel: 'chrome' }), results = [], errors = [];
const check = (name, ok) => { assert.ok(ok, name); results.push(name); console.log(`PASS ${name}`); };
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', acceptDownloads: true });
await context.addInitScript(() => localStorage.setItem('logio-cookie-consent', JSON.stringify({ value: { necessary: true }, version: '1', updatedAt: new Date().toISOString() })));
const page = await context.newPage(); page.setDefaultTimeout(30000);
page.on('pageerror', error => errors.push(error.message));
const dimensions = () => page.evaluate(() => Object.fromEntries(['.cg-stage', '.cd-root'].map(selector => { const r = document.querySelector(selector).getBoundingClientRect(); return [selector, { width: r.width, height: r.height }]; })));
try {
  await page.goto(`${base}/personalize?section=excel-formation`, { waitUntil: 'networkidle' });
  await page.locator('.storage-dropzone input[type=file]').setInputFiles({ name: 'duplicate-synthetic.xlsx', mimeType: 'application/octet-stream', buffer: Buffer.from(input) });
  await page.getByRole('tab', { name: /Review and fix/ }).click();
  await page.locator('.cd-textarea').fill('May moc thiet bi 3');
  const before = await dimensions();
  await page.getByRole('button', { name: 'Approve value', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Sửa chung các dòng trùng lỗi', exact: true });
  await dialog.waitFor();
  check('Same-asset repeated corruption is found without a conflicting-duplicate issue', /3 dòng\s*\/\s*6 ô/.test(await dialog.innerText()));
  check('Preview includes the actual hidden row', (await dialog.innerText()).includes('1 dòng ẩn'));
  const after = await dimensions();
  check('Suggestion panel dimensions are unchanged by the confirmation overlay', JSON.stringify(before) === JSON.stringify(after));
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  check('Cancel resets Approve value and keeps changes unapplied', await page.getByRole('button', { name: 'Approve value', exact: true }).isEnabled());
  await page.getByRole('button', { name: 'Approve value', exact: true }).click(); await dialog.waitFor();
  await page.setViewportSize({ width: 320, height: 900 });
  check('Group confirmation fits a 320px viewport', await dialog.evaluate(n => { const r = n.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && n.scrollWidth <= r.width + 1; }));
  await page.screenshot({ path: `${out}/confirm-320.png` });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await dialog.getByRole('button', { name: 'Áp dụng cho 3 dòng', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('button[aria-label="Redo"]')?.disabled === false);
  await page.getByRole('tab', { name: 'Export', exact: true }).click();
  const changed = () => page.locator('.cr-facts > div').filter({ has: page.getByText('Cells changed', { exact: true }) }).locator('dd').innerText();
  check('Undo reverses the whole batch', await changed() === '0');
  await page.getByRole('tab', { name: /Review and fix/ }).click(); await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('button[aria-label="Undo"]')?.disabled === false);
  await page.getByRole('tab', { name: 'Export', exact: true }).click();
  check('Redo restores all six approved cells', await changed() === '6');
  await page.getByRole('button', { name: 'Create corrected workbook', exact: true }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: /Download.*reviewed.xlsx/ }).click();
  const download = await pending; const file = `${out}/duplicate-synthetic.reviewed.xlsx`; await download.saveAs(file);
  const wb = readWorkbook(new Uint8Array(await fs.readFile(file)), { fileName: 'synthetic.xlsx', fileHash: 'test' });
  for (const r of [2, 3, 4]) for (const col of [5, 6]) assert.equal(wb.sheets[0].rows.find(row => row.r === r).cells[col].v, 'May moc thiet bi 3');
  check('Exported file contains the grouped repair on all three rows and both equivalent fields', true);
  check('Other asset with identical damaged text remains unchanged', wb.sheets[0].rows.find(row => row.r === 5).cells[5].v === 'May moc thi?t bi 3');
  check('Hidden row and lexical monetary value are preserved', wb.sheets[0].rows.find(row => row.r === 3).hidden && wb.sheets[0].rows.find(row => row.r === 3).cells[4].v === '1234.5599999999999');
  check('No browser runtime errors', errors.length === 0);
  await fs.writeFile(`${out}/results.json`, JSON.stringify({ passed: results.length, checks: results, errors, before, after }, null, 2));
  console.log(JSON.stringify({ passed: results.length }));
} catch (error) { await page.screenshot({ path: `${out}/failure.png` }).catch(() => {}); throw error; }
finally { await browser.close(); }

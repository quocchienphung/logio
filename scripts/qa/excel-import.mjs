import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { buildSmallFixture } from './lib/collateral-fixture.mjs';
import { buildXlsx } from '../../src/components/sites/collateral/excel-formation/engine/xlsx-builder.mjs';

const base = process.argv[2] || 'http://localhost:3004';
const out = 'docs/research/link-unfurl/local';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const results = [], errors = [], foreign = [];
const check = (name, ok) => { assert.ok(ok, name); results.push(name); };
const payload = (name = 'Sample workbook.xlsx') => ({ name, mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(buildSmallFixture()) });
const context = async options => {
  const ctx = await browser.newContext(options);
  await ctx.addInitScript(() => localStorage.setItem('logio-cookie-consent', JSON.stringify({ value: { necessary: true }, version: '1', updatedAt: new Date().toISOString() })));
  return ctx;
};
const open = async ctx => {
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { const u = new URL(r.url()); if (u.protocol.startsWith('http') && u.origin !== new URL(base).origin) foreign.push(r.url()); });
  await page.goto(`${base}/personalize?section=excel-formation`, { waitUntil: 'networkidle' });
  await page.locator('.cr-import').waitFor();
  await page.waitForTimeout(1300);
  await page.locator('[data-ascii-cover]').first().waitFor({ state: 'detached', timeout: 8000 });
  return page;
};
const upload = (page, file = payload()) => page.locator('input[type=file]').setInputFiles(file);
const ready = async page => { await page.getByText('Workbook opened', { exact: true }).waitFor({ timeout: 30000 }); await page.locator('.import-unfurl__grid td').first().waitFor({ state: 'visible' }); await page.waitForTimeout(100); };
try {
  const desktop = await context({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const page = await open(desktop);
  const alignment = await page.locator('.cr-import').evaluate(n => {
    const r = n.getBoundingClientRect(), c = n.firstElementChild.getBoundingClientRect();
    return { dx: Math.abs(c.x + c.width / 2 - r.x - r.width / 2), dy: Math.abs(c.y + c.height / 2 - r.y - r.height / 2) };
  });
  check('Idle upload group is centered in the remaining workspace content, both axes', alignment.dx < 1 && alignment.dy < 1);
  check('The accepted format and both illustration badges say XLSX', await page.locator('input[type=file]').getAttribute('accept') === '.xlsx' && (await page.locator('.storage-dropzone__badge text').allTextContents()).every(text => text === 'XLSX'));
  await page.screenshot({ path: `${out}/desktop-idle.png` });
  await page.locator('.storage-dropzone__area').focus();
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.keyboard.press('Enter')]);
  await chooser.setFiles({ name: 'wrong.csv', mimeType: 'text/csv', buffer: Buffer.from('x,y') });
  await page.locator('.import-unfurl__error').waitFor();
  check('Keyboard browse works; a CSV is refused with the actual engine error', (await page.locator('.import-unfurl__error').innerText()).includes('.xlsx'));
  check('Failed file offers retry and replacement', await page.getByRole('button', { name: 'Retry', exact: true }).isVisible() && await page.getByRole('button', { name: 'Choose another file', exact: true }).isVisible());
  await page.screenshot({ path: `${out}/desktop-error.png` });
  await upload(page, { name: 'broken.xlsx', mimeType: 'application/octet-stream', buffer: Buffer.from('not a zip') });
  await page.locator('.import-unfurl__body h2').filter({ hasText: 'broken.xlsx' }).waitFor();
  await page.locator('.import-unfurl__error').waitFor();
  check('Malformed XLSX is refused; ready is never fabricated', await page.getByText('Workbook opened', { exact: true }).count() === 0);
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await page.locator('.import-unfurl__error').waitFor();
  check('Retry returns the real parse failure', await page.locator('.import-unfurl__error').isVisible());
  await upload(page);
  await ready(page);
  await page.waitForTimeout(1550);
  check('Import remains selected after the old automatic-advance delay', await page.getByRole('tab', { name: /Import/ }).getAttribute('aria-selected') === 'true');
  check('Preview shows actual sheet, four data rows and cell content from the synthetic file', (await page.locator('.import-unfurl__media').innerText()).includes('MAU9_TEST') && (await page.locator('.import-unfurl__media').innerText()).includes('4 Data rows') && (await page.locator('.import-unfurl__grid').innerText()).includes('30/09/2026'));
  const sizes = await page.locator('.import-unfurl').evaluate(n => ({ composer: n.querySelector('.import-unfurl__composer').getBoundingClientRect().width, card: n.querySelector('article').getBoundingClientRect().width, chip: n.querySelector('.import-unfurl__chip').getBoundingClientRect().height, head: n.querySelector('header').getBoundingClientRect().height }));
  check('Measured source dimensions are retained: 576/440/26/30 px', sizes.composer === 576 && sizes.card === 440 && sizes.chip === 26 && sizes.head === 30);
  await page.screenshot({ path: `${out}/desktop-ready.png` });
  await page.getByRole('button', { name: 'Collapse workbook preview', exact: true }).click();
  await page.waitForTimeout(130);
  const during = await page.locator('.import-unfurl__lane').evaluate(n => n.getBoundingClientRect().height);
  check('Collapse passes through a measured intermediate height', during > 1 && during < 330);
  await page.waitForTimeout(1200);
  check('Folded preview is inert and excluded from accessibility; focus returns to chip', await page.locator('article.import-unfurl__card').getAttribute('inert') !== null && await page.locator('article.import-unfurl__card').getAttribute('aria-hidden') === 'true' && await page.locator('.import-unfurl__chip').evaluate(n => document.activeElement === n));
  await page.keyboard.press('Enter');
  await page.waitForTimeout(1550);
  check('Enter reopens the preview', await page.locator('.import-unfurl__chip').getAttribute('aria-expanded') === 'true');
  const head = await page.locator('.import-unfurl__head').boundingBox();
  await page.mouse.move(head.x + 70, head.y + 15); await page.mouse.down();
  await page.mouse.move(head.x + 70, head.y - 180, { steps: 8 }); await page.mouse.up();
  await page.waitForTimeout(1200);
  check('Dragging the header upward folds the card', await page.locator('.import-unfurl__chip').getAttribute('aria-expanded') === 'false');
  await page.locator('.import-unfurl__chip').click(); await page.waitForTimeout(1500);
  await page.getByRole('button', { name: 'See what was found', exact: true }).click();
  await page.locator('.cr-overview').waitFor();
  check('Continue opens the existing Overview', await page.getByRole('tab', { name: /Overview/ }).getAttribute('aria-selected') === 'true');
  await page.getByRole('tab', { name: /Review and fix/ }).click(); await page.locator('.cr-review').waitFor();
  check('The existing Review step still opens with the workbook', await page.locator('.cr-review').isVisible());
  await page.getByRole('tab', { name: /Export/ }).click(); await page.locator('.cr-export').waitFor();
  check('The existing Export step still opens', await page.getByRole('heading', { name: 'Corrected workbook', exact: true }).isVisible());
  await page.locator('.ui-as-side__nav').getByRole('button', { name: 'JSON formation', exact: true }).click();
  await page.locator('#json-panel').waitFor();
  check('JSON formation retains the shared workbook after leaving Excel', await page.locator('h1').innerText() === 'JSON formation' && await page.locator('.cl-file').count() === 1);
  await page.locator('.ui-as-side__nav').getByRole('button', { name: /^Excel formation/ }).click();
  await page.locator('.import-unfurl').waitFor();
  await page.getByRole('tab', { name: /Import/ }).click();
  await page.getByRole('button', { name: 'Remove workbook', exact: true }).click();
  await page.locator('.storage-dropzone__area').waitFor();
  check('Remove clears the workbook and restores keyboard focus to browse', await page.locator('.storage-dropzone__area').evaluate(n => document.activeElement === n));
  // A larger synthetic file keeps the real worker busy long enough to exercise Cancel.
  const large = buildXlsx([{ name: 'Test', rows: [Array.from({ length: 12 }, (_, i) => `COLUMN_${i}`), ...Array.from({ length: 24000 }, (_, i) => Array.from({ length: 12 }, (_, j) => `TEST_${i}_${j}`))] }]);
  await upload(page, { name: 'large.xlsx', mimeType: 'application/octet-stream', buffer: Buffer.from(large) });
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.locator('.storage-dropzone__area').waitFor();
  await page.waitForTimeout(500);
  check('Cancel terminates real worker processing and keeps Import usable', await page.locator('.storage-dropzone__area').isEnabled() && await page.locator('.import-unfurl').count() === 0);
  await desktop.close();

  for (const [width, height] of [[1920, 1080], [768, 900], [390, 844], [320, 740], [1280, 600]]) {
    const ctx = await context({ viewport: { width, height }, hasTouch: width < 600, reducedMotion: 'reduce' });
    const p = await open(ctx);
    const bounds = await p.locator('.storage-dropzone__area').boundingBox();
    check(`Upload visible and no horizontal overflow at ${width}×${height}`, bounds.y >= 0 && bounds.y + bounds.height <= height && await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await p.screenshot({ path: `${out}/${width}-idle.png` });
    await upload(p, payload('Long workbook name with Unicode — Đối soát dữ liệu.xlsx')); await ready(p);
    check(`Actual file preview has no horizontal overflow at ${width}px`, await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.querySelector('.import-unfurl').scrollWidth <= document.querySelector('.import-unfurl').clientWidth));
    check(`Cell preview keeps a readable scrollable area at ${width}px`, await p.locator('.import-unfurl__grid').evaluate(n => n.getBoundingClientRect().height >= 134));
    await p.screenshot({ path: `${out}/${width}-ready.png`, fullPage: true });
    await p.getByRole('button', { name: 'Collapse workbook preview', exact: true }).click();
    check(`Reduced motion lands folded immediately at ${width}px`, await p.locator('.import-unfurl__lane').evaluate(n => n.getBoundingClientRect().height < 1));
    await ctx.close();
  }
  const dark = await context({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark', reducedMotion: 'reduce' });
  await dark.addInitScript(() => localStorage.setItem('affectui:preferences', JSON.stringify({ dark: true, theme: 'dark' })));
  const dp = await open(dark); await upload(dp); await ready(dp);
  await dp.screenshot({ path: `${out}/desktop-dark.png` });
  check('Dark theme reaches the file preview', await dp.locator('.crm-page').getAttribute('data-theme') === 'dark');
  await dark.close();
  const vi = await context({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  await vi.addInitScript(() => localStorage.setItem('affectui:interface-language', JSON.stringify('vi')));
  const vp = await open(vi);
  check('New import copy supports Vietnamese without editing shared dictionaries', await vp.getByText('Bắt đầu với tệp Excel của bạn', { exact: true }).isVisible());
  await vp.screenshot({ path: `${out}/390-vi.png` }); await vi.close();
  check('No browser exceptions', errors.length === 0);
  check('No external network requests during local workbook workflows', foreign.length === 0);
  console.log(`${results.length} checks passed`);
} catch (error) { console.error('FAILED after:', results.at(-1), error); process.exitCode = 1; }
finally { await fs.writeFile(`${out}/results.json`, JSON.stringify({ base, results, errors, foreign }, null, 2)); await browser.close(); }

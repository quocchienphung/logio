import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { installBundle } from '../skilled/install-bundle.mjs';

const base = process.argv[2] || 'http://localhost:3000';
const out = 'docs/research/uiarc-skilled';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const results = [], errors = [];
const check = (name, result) => { assert.ok(result, name); results.push(name); };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/skilled`, { waitUntil: 'networkidle' });
  await page.getByRole('region', { name: 'Skilled workspace', exact: true }).waitFor();
  await page.screenshot({ path: `${out}/local-desktop.png` });
  check('Workspace sidebar owns Skilled', await page.getByRole('navigation', { name: 'Main menu' }).getByRole('button', { name: 'Skilled' }).getAttribute('aria-current') === 'page');
  check('No invented initial readings', await page.locator('.sk-metrics strong').first().innerText() === '0');
  await page.getByLabel('Skill instructions', { exact: true }).fill('Use observed source evidence. Verify every factual claim.');
  await page.getByLabel('Skill name', { exact: true }).fill('evidence-first');
  await page.getByLabel('Description', { exact: true }).fill('Use for factual research requiring traceable evidence.');
  await page.getByRole('button', { name: 'Add skill', exact: true }).click();
  await page.locator('.sk-card').first().waitFor();
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('affectui:acme:skill-events') || '[]').some(event => event.kind === 'save'));
  check('Actual save operation recorded', await page.locator('.sk-activity').innerText().then(text => text.includes('Browser save')));
  await page.reload({ waitUntil: 'networkidle' });
  check('Skill persists after reload', await page.locator('.sk-card-title').innerText().then(text => text.includes('evidence-first')));
  await page.getByRole('button', { name: 'evidence-first', exact: true }).click();
  check('Details include provenance and instructions', await page.locator('.sk-card-details').innerText().then(text => text.includes('SHA-256') && text.includes('Verify every factual claim')));
  await page.screenshot({ path: `${out}/local-skill-expanded.png` });
  await page.getByRole('button', { name: 'Deliver', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Deliver skills' });
  check('Remote transfer disabled without backend', await dialog.getByRole('button', { name: 'Transfer & verify receipt' }).isDisabled());
  const downloaded = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Export 1 skill' }).click();
  const download = await downloaded;
  const stream = await download.createReadStream();
  let raw = ''; for await (const chunk of stream) raw += chunk;
  const bundle = JSON.parse(raw);
  check('Bundle contains exact selected instruction and guardrails', bundle.skills.length === 1 && bundle.skills[0].guardrails.citeSources && bundle.skills[0].instructions.includes('Verify every factual claim'));
  const temp = await fs.mkdtemp(`${process.env.TEMP || process.env.TMP || '.'}/logio-skilled-`);
  const installed = await installBundle(bundle, { directory: `${temp}/skills` });
  check('Local installer preserves SKILL.md', await fs.readFile(`${installed.directory}/evidence-first/SKILL.md`, 'utf8') === bundle.skills[0].instructions);
  check('Local installer emits guardrails', (await fs.readFile(`${installed.directory}/evidence-first/LOGIO.md`, 'utf8')).includes('Cite supporting sources'));
  await page.getByRole('button', { name: 'Deliver', exact: true }).click();
  await dialog.locator('input[type=file]').setInputFiles(`${installed.directory}/transfer-receipt.json`);
  await page.getByRole('status').filter({ hasText: 'Receipt imported' }).waitFor();
  check('Offline receipt recorded without claiming model loading', await page.locator('.sk-notice').innerText().then(text => text.includes('execution remain unverified')));
  await page.getByRole('button', { name: 'Archive evidence-first' }).click();
  await page.getByRole('tab', { name: /Archived/ }).click();
  check('Archive filter works', await page.getByRole('button', { name: 'Restore', exact: true }).isVisible());
  await page.getByRole('button', { name: 'Restore', exact: true }).click();
  await page.getByRole('tab', { name: /All skills/ }).click();
  await page.getByLabel('Search skills').fill('not-present');
  check('Search empty state works', await page.getByRole('heading', { name: 'No skills in this view' }).isVisible());
  await page.getByLabel('Search skills').fill('');
  await page.getByRole('button', { name: 'Attributes', exact: true }).click();
  await page.getByLabel('GitHub repository or skill URL', { exact: false }).fill('https://github.com/anthropics/skills/blob/main/skills/webapp-testing/SKILL.md');
  await page.getByLabel('Skill instructions', { exact: true }).fill('Prioritize primary source evidence for this workspace.');
  await page.getByRole('button', { name: 'Add skill', exact: true }).click();
  await page.getByRole('button', { name: 'webapp-testing', exact: true }).waitFor({ timeout: 30000 });
  check('Real GitHub raw import succeeds', await page.locator('.sk-card').count() === 2);
  const importedFolder = await page.evaluate(() => JSON.parse(localStorage.getItem('affectui:acme:skill-library') || '[]').find(skill => skill.name === 'webapp-testing'));
  check('GitHub scan includes supporting scripts and pins the captured commit', importedFolder?.files?.some(file => file.path.startsWith('scripts/')) && /^[a-f0-9]{40}$/.test(importedFolder.sourceRef));
  check('Form instructions alongside a GitHub source are preserved', importedFolder.files.some(file => file.path === 'WORKSPACE-INSTRUCTIONS.md' && file.content.includes('Prioritize primary source evidence')));
  const folderCard = page.locator('.sk-card').filter({ has: page.getByRole('button', { name: 'webapp-testing', exact: true }) });
  await folderCard.getByRole('button', { name: 'Deliver', exact: true }).click();
  const folderDownloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Export 1 skill' }).click();
  const folderDownload = await folderDownloadPromise;
  const folderStream = await folderDownload.createReadStream(); let folderRaw = '';
  for await (const chunk of folderStream) folderRaw += chunk;
  const folderInstalled = await installBundle(JSON.parse(folderRaw), { directory: `${temp}/complete-folder` });
  const supporting = importedFolder.files.find(file => file.path.startsWith('scripts/') && file.encoding === 'utf8');
  check('Export and local installer preserve actual GitHub supporting scripts', await fs.readFile(`${folderInstalled.directory}/webapp-testing/${supporting.path}`, 'utf8') === supporting.content);
  await folderCard.getByRole('button', { name: 'Deliver', exact: true }).click();
  await dialog.locator('input[type=file]').setInputFiles(`${folderInstalled.directory}/transfer-receipt.json`);
  await page.getByRole('status').filter({ hasText: 'Receipt imported' }).waitFor();
  check('Full-folder receipt validates supporting file hashes', await page.locator('.sk-notice').innerText().then(text => text.includes('Receipt imported')));
  const localInstructions = '---\nname: local-skill\ndescription: Preserve a local instruction file.\n---\n\nCheck the evidence before responding.\n';
  await page.locator('.sk-composer input[type=file]').setInputFiles({ name: 'SKILL.md', mimeType: 'text/markdown', buffer: Buffer.from(localInstructions) });
  await page.getByRole('button', { name: 'Add skill', exact: true }).click();
  await page.getByRole('button', { name: 'local-skill', exact: true }).waitFor();
  await page.waitForFunction(expected => JSON.parse(localStorage.getItem('affectui:acme:skill-library') || '[]').some(skill => skill.name === 'local-skill' && skill.instructions === expected), localInstructions);
  check('Local SKILL.md keeps its exact contents and frontmatter', true);
  const bad = await page.request.post(`${base}/api/skilled/import`, { data: { url: 'http://127.0.0.1/private' } });
  check('Importer rejects non-GitHub URL', bad.status() === 400);
  await page.screenshot({ path: `${out}/local-desktop-populated.png` });
  const plot = page.getByRole('group', { name: /Operation duration/ });
  await plot.focus(); await page.keyboard.press('Home');
  check('Chart supports keyboard point reading', await page.locator('.skilled-stream-tooltip').isVisible());
  await page.keyboard.press('Escape');
  await page.locator('.skilled-stream-status').click();
  check('Chart can pause', await page.locator('.skilled-stream-status').getAttribute('aria-pressed') === 'true');
  await page.locator('.skilled-stream-status').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${out}/local-mobile.png`, fullPage: true });
  check('Mobile has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Open sidebar' }).click();
  await page.getByRole('navigation', { name: 'Main menu' }).getByRole('button', { name: 'Skilled' }).waitFor({ state: 'visible' });
  check('Mobile sidebar opens', await page.locator('.ui-as-app').getAttribute('data-drawer') !== null);
  await context.close();

  // A controlled backend verifies the transport, not a real deployed agent.
  const remote = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await remote.addInitScript(() => { window.__workspaceBackendConfig = { baseUrl: 'https://logio-backend.test', debounceMs: 10 }; });
  const persisted = new Map(); let receiptMatches = false; let transfers = 0;
  await remote.route('https://logio-backend.test/**', async route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname;
    if (request.method() === 'PUT') { persisted.set(path, request.postDataJSON().data); await route.fulfill({ status: 204 }); return; }
    if (path.endsWith('/commands/skill.transfer')) {
      transfers++; const { bundle, agent } = request.postDataJSON();
      const receipt = { bundleVersion: 1, workspaceId: bundle.workspaceId, receivedAt: new Date().toISOString(), agent, accepted: bundle.skills.map(skill => ({ id: skill.id, sha256: receiptMatches ? skill.sha256 : '0'.repeat(64), ...(skill.files ? { files: skill.files.map(file => ({path:file.path,sha256:file.sha256})) } : {}) })), bytes: bundle.skills.reduce((sum, skill) => sum + skill.bytes + (skill.files || []).reduce((total, file) => total + file.bytes, 0), 0) };
      await route.fulfill({ json: { data: receipt } }); return;
    }
    await route.fulfill(persisted.has(path) ? { json: { data: persisted.get(path) } } : { status: 404 });
  });
  const r = await remote.newPage(); r.on('pageerror', error => errors.push(error.message));
  await r.goto(`${base}/skilled`, { waitUntil: 'networkidle' });
  await r.getByLabel('Skill instructions', { exact: true }).fill('Check sources before responding.');
  await r.getByLabel('Skill name', { exact: true }).fill('remote-evidence');
  await r.getByLabel('Description', { exact: true }).fill('Research with evidence.');
  await r.getByRole('button', { name: 'Add skill', exact: true }).click();
  await r.waitForFunction(() => document.querySelector('.sk-activity')?.textContent.includes('Database save'));
  check('REST resource written to configured workspace', persisted.get('/workspaces/acme/skill-library')?.[0].name === 'remote-evidence');
  await r.getByRole('button', { name: 'Deliver', exact: true }).click();
  const rd = r.getByRole('dialog', { name: 'Deliver skills' });
  await rd.getByLabel('Agent ID').fill('research-agent');
  await rd.getByRole('button', { name: 'Transfer & verify receipt' }).click();
  await r.getByRole('alert').filter({ hasText: 'Delivery is unconfirmed' }).waitFor();
  check('Mismatched receipt never confirms transfer', transfers === 1 && !await r.locator('.sk-notice').innerText().then(text => text.includes('Receipt confirmed')));
  receiptMatches = true;
  await rd.getByRole('button', { name: 'Transfer & verify receipt' }).click();
  await r.getByRole('status').filter({ hasText: 'Receipt confirmed by research-agent' }).waitFor();
  check('Matching receipt confirms transport only', transfers === 2 && await r.locator('.sk-notice').innerText().then(text => text.includes('does not verify model behavior')));
  await r.screenshot({ path: `${out}/local-connected-receipt.png` });
  check('No browser runtime errors', errors.length === 0);
  await remote.close();
  console.log(`${results.length} checks passed.`);
} finally {
  await fs.writeFile(`${out}/qa-results.json`, JSON.stringify({ results, errors }, null, 2));
  await browser.close();
}

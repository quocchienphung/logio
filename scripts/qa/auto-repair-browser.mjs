import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { chromium } from "playwright";
import { repairFixture } from "../../src/components/sites/collateral/excel-formation/engine/auto-repair-fixture.mjs";
import { zeroPatchWorkbook, HEADERS } from "../../src/components/sites/collateral/excel-formation/engine/zero-patch-fixture.mjs";
import { buildXlsx } from "../../src/components/sites/collateral/excel-formation/engine/xlsx-builder.mjs";
import { comparePackages, diffCells } from "../../src/components/sites/collateral/excel-formation/engine/ooxml-independent.mjs";
import { buildFixture } from "./lib/collateral-fixture.mjs";
import { readWorkbook } from "../../src/components/sites/collateral/excel-formation/engine/xlsx-reader.ts";
const base = process.argv[2] ?? 'http://localhost:3002', out = 'docs/auto-repair/browser';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' }), checks = [], errors = [], uploads = [], external = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); console.log(`PASS ${name}`); };
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
await context.addInitScript(() => { localStorage.setItem('logio-cookie-consent', JSON.stringify({ value: { necessary: true }, version: '1', updatedAt: new Date().toISOString() })); });
const page = await context.newPage();
page.setDefaultTimeout(30000);
page.setDefaultNavigationTimeout(60000);
page.on('pageerror', error => errors.push(error.message));
page.on('request', r => { if (['POST', 'PUT', 'PATCH'].includes(r.method()) && /collateral|queue/.test(r.url())) uploads.push(r.method()); if (/^https?:/.test(r.url()) && !r.url().startsWith(base)) external.push(new URL(r.url()).hostname); });
page.on('dialog', dialog => dialog.dismiss());
const downloads = [];
let workerMeasurement = null;
page.on('download', async d => { const path = `${out}/${d.suggestedFilename()}`; await d.saveAs(path); downloads.push({ name: d.suggestedFilename(), path }); });
const upload = async (buffer, name = 'synthetic.xlsx') => {
  console.log(`STEP choose ${name}`);
  await page.locator('.storage-dropzone input[type=file]').setInputFiles({ name, mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(buffer) });
  console.log(`STEP await parse ${name}`);
  await page.getByRole('button', { name: 'Tự động sửa Excel', exact: true }).waitFor({ timeout: 120000 });
  await page.waitForFunction(() => document.querySelector('.cr-auto-trigger')?.disabled === false, { timeout: 120000 });
};
try {
  await page.goto(`${base}/personalize?section=excel-formation`, { waitUntil: 'networkidle' });
  await upload(repairFixture());
  check('No original upload after selecting a local file', uploads.length === 0);
  const trigger = page.getByRole('button', { name: 'Tự động sửa Excel', exact: true });
  check('One-click action enabled after valid parse/profile', await trigger.isEnabled());
  await context.setOffline(true);
  await trigger.click();
  await page.locator('[data-repair-status]').waitFor({ timeout: 30000 });
  await page.waitForFunction(() => document.querySelector('[data-repair-status]')?.textContent?.includes('một phần'));
  for (let i = 0; i < 50 && downloads.length < 2; i++) await page.waitForTimeout(100);
  check('One click works offline and produces both real local downloads', downloads.length === 2 && uploads.length === 0);
  const xlsx = downloads.find(d => d.name.endsWith('.xlsx')), reportFile = downloads.find(d => d.name.endsWith('.json'));
  const report = JSON.parse(await fs.readFile(reportFile.path, 'utf8'));
  check('Result is accurately labelled partial, with all sheets accounted', report.status === 'REPAIRED_PARTIALLY' && report.applied === 2 && report.unresolved === 7 && report.sheets.length === 2);
  const wb = readWorkbook(new Uint8Array(await fs.readFile(xlsx.path)), { fileName: xlsx.name, fileHash: 'browser-test' });
  check('Downloaded XLSX contains approved source text and preserves protected fields', wb.sheets[0].rows.find(r => r.r === 4).cells[5].v === 'can ho bay tang 3' && wb.sheets[0].rows[1].cells[0].v === '00001' && wb.sheets[1].rows[0].cells[2].f);
  await page.screenshot({ path: `${out}/result-desktop.png` });
  await page.getByRole('button', { name: 'Close Tự động sửa Excel', exact: true }).click();
  await context.setOffline(false);
  await page.getByRole('tab', { name: /Review and fix/ }).click();
  await page.locator('.cg-stage').waitFor();
  check('Review exposes one atomic undo for automatic repair', await page.getByRole('button', { name: 'Undo', exact: true }).isEnabled());
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('button[aria-label="Redo"]')?.disabled === false);
  check('Undo enables redo', await page.getByRole('button', { name: 'Redo', exact: true }).isEnabled());
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('button[aria-label="Undo"]')?.disabled === false);
  await page.screenshot({ path: `${out}/review-desktop.png` });
  const geometry = async () => page.evaluate(() => {
    const selectors = ['.cg-stage', '.cd-root', '.cg-rail'];
    return Object.fromEntries(selectors.map(s => { const n = document.querySelector(s); if (!n) return [s, null]; const r = n.getBoundingClientRect(); return [s, { x: r.x, y: r.y, w: r.width, h: r.height }]; }));
  });
  const shown = await geometry();
  await trigger.evaluate(n => { n.style.display = 'none'; });
  const hidden = await geometry();
  check('Header action leaves desktop suggestion geometry unchanged', JSON.stringify(shown) === JSON.stringify(hidden));
  await page.locator('.cr-auto-trigger').evaluate(n => { n.style.display = ''; });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 900 }); await page.waitForTimeout(250);
    check(`Review does not overflow horizontally at ${width}px`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({ path: `${out}/review-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  console.log('STEP close first file');
  await page.getByRole('button', { name: 'Close file', exact: true }).click();
  console.log('STEP upload suggestions fixture');
  await page.screenshot({ path: `${out}/after-close.png`, timeout: 10000 });
  await upload(buildFixture(), 'suggestions.xlsx');
  await page.getByRole('tab', { name: /Review and fix/ }).click();
  await page.locator('.cg-stage').waitFor();
  check('Existing suggestion stage and details remain mounted', await page.locator('.cd-root').count() === 1 && await page.locator('.cg-stage').count() === 1);
  await page.screenshot({ path: `${out}/suggestions-unchanged.png`, fullPage: true });
  // Large input uses the actual browser worker and real cancel request, never a mocked RPC.
  try {
    const large = await fs.readFile('docs/auto-repair/synthetic-artifacts/large.xlsx');
    console.log('STEP upload large fixture');
    await page.getByRole('button', { name: 'Close file', exact: true }).click();
    await upload(large, 'large-synthetic.xlsx');
    await page.evaluate(() => { window.__repairTicks = 0; window.__repairTimer = setInterval(() => window.__repairTicks++, 10); });
    await trigger.click();
    const cancelStarted = Date.now();
    await page.getByRole('button', { name: 'Hủy', exact: true }).click();
    await page.locator('.cr-auto-result [role=alert]').waitFor({ timeout: 30000 });
    const ticks = await page.evaluate(() => { clearInterval(window.__repairTimer); return window.__repairTicks; });
    workerMeasurement = { mainThreadTicks: ticks, timerIntervalMs: 10, cancellationMs: Date.now() - cancelStarted, inputRows: 50000 };
    check('Large worker run responds to cancellation, main thread still ticks', ticks > 0 && (await page.locator('.cr-auto-result').innerText()).includes('cancelled'));
    check('Cancellation does not produce a workbook or report', downloads.length === 2);
    await page.keyboard.press('Escape');
    await page.getByRole('tab', { name: /Review and fix/ }).click();
    check('Cancellation leaves original review history intact', await page.getByRole('button', { name: 'Undo', exact: true }).isDisabled());
  } catch (error) { if (error.code === 'ENOENT') throw new Error('Run the 50k benchmark before browser cancellation QA.'); throw error; }
  // The zero-patch bug, end to end in the browser: click -> worker -> download -> independent parser.
  console.log('STEP close suggestions file');
  await page.getByRole('button', { name: 'Close file', exact: true }).click();
  const modelInput = zeroPatchWorkbook(), downloadsBefore = downloads.length;
  await upload(modelInput, 'model.xlsx');
  await page.getByRole('button', { name: 'Tự động sửa Excel', exact: true }).click();
  await page.locator('[data-repair-status]').waitFor({ timeout: 60000 });
  for (let i = 0; i < 80 && downloads.length < downloadsBefore + 2; i++) await page.waitForTimeout(100);
  const repaired = downloads.slice(downloadsBefore).find(d => d.name.endsWith('.repaired.xlsx'));
  check('Model path: the button produced a .repaired.xlsx', !!repaired && await page.locator('[data-repair-status]').getAttribute('data-repair-status') === 'REPAIRED_PARTIALLY');
  const outBytes = new Uint8Array(await fs.readFile(repaired.path)), diff = diffCells(modelInput, outBytes);
  check('Independent parser confirms changed cells in the downloaded file and no structural change', comparePackages(modelInput, outBytes).verdict === 'CONTENT_CHANGED' && diff.changed.length === 8 && diff.structural.length === 0);
  await page.screenshot({ path: `${out}/model-result.png` });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Close file', exact: true }).click();
  const tiny = buildXlsx([{ name: 'S', rows: [HEADERS, ['00001', 'K1', 'A1', '303', { n: '1' }, 'm?y moc', 'm?y moc', 'Synthetic Person'], ['00001', 'K2', 'A2', '303', { n: '1' }, 'may moc', 'may moc', 'Synthetic Person']] }]);
  const beforeTiny = downloads.length;
  await upload(tiny, 'tiny.xlsx');
  await page.getByRole('button', { name: 'Tự động sửa Excel', exact: true }).click();
  await page.locator('[data-repair-status]').waitFor({ timeout: 60000 });
  await page.waitForTimeout(800);
  const status = await page.locator('[data-repair-status]').getAttribute('data-repair-status'), text = await page.locator('[data-repair-status]').innerText();
  check('Nothing provable: NO_REPAIR_APPLIED, honest text, no automatic download', status === 'NO_REPAIR_APPLIED' && /Chưa sửa/.test(text) && !/Đã sửa/.test(text) && downloads.length === beforeTiny);
  await page.screenshot({ path: `${out}/no-repair-result.png` });
  await page.keyboard.press('Escape');
  check('No page errors', errors.length === 0);
  check('No external requests and no automatic archive calls', external.length === 0 && uploads.length === 0);
  await fs.writeFile(`${out}/results.json`, JSON.stringify({ passed: checks.length, checks, errors, externalRequests: external.length, automaticUploads: uploads.length, suggestionGeometry: shown, workerMeasurement }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks }));
} catch (error) {
  await page.screenshot({ path: `${out}/failure.png`, fullPage: true }).catch(() => {});
  await fs.writeFile(`${out}/failure.json`, JSON.stringify({ passed: checks, errors, message: error.message, inputs: await page.locator('input[type=file]').evaluateAll(nodes => nodes.map(n => ({ accept: n.accept, label: n.getAttribute('aria-label'), parent: n.parentElement?.className }))).catch(() => []) }, null, 2));
  throw error;
} finally { await browser.close(); }

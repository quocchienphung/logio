// Exports the logos the public Delegate Board preview draws (https://www.affectui.com/components/delegate-board)
// into src/components/sites/affectui-delegate-board/brand-icons.generated.ts. Only inline SVG that the preview page
// itself renders is read; nothing from the Pro code, CLI, registry or an authenticated endpoint.
// Usage: node scripts/forensics/affectui-delegate-board-icons.mjs
import fs from 'node:fs/promises';
import { chromium } from 'playwright';

const target = 'src/components/sites/affectui-delegate-board/brand-icons.generated.ts';
const browser = await chromium.launch({ channel: 'chrome' });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
await page.goto('https://www.affectui.com/components/delegate-board', { waitUntil: 'networkidle' });
await page.waitForSelector('.ui-dbc__agent', { timeout: 30000 });
await page.waitForTimeout(1200);

const found = await page.evaluate(() => {
  const root = document.querySelector('.ui-dbc');
  const read = svg => svg && { viewBox: svg.getAttribute('viewBox'), fill: svg.getAttribute('fill'), style: svg.getAttribute('style'), html: svg.innerHTML };
  const agent = name => [...root.querySelectorAll('.ui-dbc__agent')].find(a => a.querySelector('.ui-dbc__name')?.textContent === name);
  const task = title => [...root.querySelectorAll('.ui-dbc__task')].find(t => t.querySelector('.ui-dbc__task-title')?.textContent === title);
  const tool = (title, index) => read(task(title)?.querySelectorAll('.ui-dbc__tool svg')[index]);
  const chip = (agentName, label, index) => read([...agent(agentName).querySelectorAll('.ui-dbc__chip')].find(c => c.textContent.includes(label))?.querySelectorAll('svg')[index]);
  return {
    anthropic: read(agent('Researcher')?.querySelector('.ui-dbc__avatar svg')),
    openai: read(agent('Coder')?.querySelector('.ui-dbc__avatar svg')),
    gemini: read(agent('Ops')?.querySelector('.ui-dbc__avatar svg')),
    notion: tool('Write release notes', 0),
    github: tool('Write release notes', 1),
    githubAgain: tool('Fix flaky checkout test', 0),
    slack: tool('Summarize churn calls', 0),
    figma: tool('Update pricing page', 0),
    hubspot: tool('Clean up CRM duplicates', 0),
    stripe: chip('Coder', 'Upgrade Stripe SDK', 0),
  };
});
await browser.close();

for (const [id, icon] of Object.entries(found)) if (!icon?.viewBox || !icon.html) throw new Error(`No SVG found for ${id}; the preview markup changed.`);
if (found.github.html !== found.githubAgain.html) throw new Error('The two GitHub marks differ.');
delete found.githubAgain;

// Static markup is rendered with dangerouslySetInnerHTML, so only drawing elements and no scripting are allowed.
const allowedTags = new Set(['path', 'g', 'defs', 'lineargradient', 'stop', 'rect', 'circle', 'clippath']);
for (const [id, icon] of Object.entries(found)) {
  for (const [, tag] of icon.html.matchAll(/<\s*([a-zA-Z][\w-]*)/g)) if (!allowedTags.has(tag.toLowerCase())) throw new Error(`${id}: unexpected <${tag}>`);
  if (/\bon\w+\s*=|javascript:|href\s*=|<script/i.test(icon.html)) throw new Error(`${id}: scripting or links in SVG`);
}

const entries = Object.entries(found).map(([id, icon]) => {
  const mono = /var\(--ui-dbc-strong/.test(icon.style || '');
  const html = icon.html.replace(/id="gm_r_2_"/g, 'id="dgb-gemini"').replace(/url\(#gm_r_2_\)/g, 'url(#dgb-gemini)');
  return `  ${id}: { viewBox: ${JSON.stringify(icon.viewBox)}, fill: ${JSON.stringify(icon.fill)}, mono: ${mono}, html: ${JSON.stringify(html)} },`;
});
const ids = Object.keys(found).map(id => JSON.stringify(id)).join(' | ');
await fs.writeFile(target, `// Generated by scripts/forensics/affectui-delegate-board-icons.mjs from the public Delegate Board preview. Do not edit by hand.
// \`mono\` marks the black marks that follow the text color (white in dark mode); the others keep their brand colors.
export type BrandIconId = ${ids};
export type BrandIcon = { viewBox: string; fill: string | null; mono: boolean; html: string };

export const brandIcons: Record<BrandIconId, BrandIcon> = {
${entries.join('\n')}
};
`);
console.log(`Wrote ${Object.keys(found).length} icons to ${target}`);

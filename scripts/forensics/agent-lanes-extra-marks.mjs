// Fetches the Hermes Agent and Ollama marks from the published @lobehub/icons-static-svg package (MIT, pinned version)
// and writes them to src/components/sites/affectui-agent-lanes/extra-marks.generated.ts. Static SVG only: nothing is
// executed or copied from affectUI, and no mark is drawn by hand.
// Usage: node scripts/forensics/agent-lanes-extra-marks.mjs
import fs from 'node:fs/promises';

const version = '1.95.1';
const marks = { hermes: 'hermesagent', ollama: 'ollama' };
const target = 'src/components/sites/affectui-agent-lanes/extra-marks.generated.ts';

const license = await (await fetch(`https://registry.npmjs.org/@lobehub/icons-static-svg/${version}`)).json();
if (license.license !== 'MIT') throw new Error(`Unexpected license ${license.license}`);

const entries = [];
for (const [id, file] of Object.entries(marks)) {
  const url = `https://unpkg.com/@lobehub/icons-static-svg@${version}/icons/${file}.svg`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} -> ${response.status}`);
  const svg = await response.text();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const title = svg.match(/<title>([^<]+)<\/title>/)?.[1];
  const body = svg.replace(/^[\s\S]*?<title>[^<]*<\/title>/, '').replace(/<\/svg>\s*$/, '');
  if (!viewBox || !title || !body.includes('<path')) throw new Error(`${file}: unexpected markup`);
  // Only drawing paths and no scripting: the markup is rendered with dangerouslySetInnerHTML.
  for (const [, tag] of body.matchAll(/<\s*([a-zA-Z][\w-]*)/g)) if (tag.toLowerCase() !== 'path') throw new Error(`${file}: unexpected <${tag}>`);
  if (/\bon\w+\s*=|javascript:|href\s*=|<script|style\s*=/i.test(body)) throw new Error(`${file}: scripting, links or styles in SVG`);
  entries.push(`  ${id}: { title: ${JSON.stringify(title)}, viewBox: ${JSON.stringify(viewBox)}, html: ${JSON.stringify(body)} },`);
}

await fs.writeFile(target, `// Generated by scripts/forensics/agent-lanes-extra-marks.mjs. Do not edit by hand.
// Source: @lobehub/icons-static-svg@${version} (MIT, https://github.com/lobehub/lobe-icons), icons/hermesagent.svg and icons/ollama.svg.
// Both marks are single-color (they follow the text color); \`html\` holds only <path> elements.
export type ExtraMarkId = ${Object.keys(marks).map(id => JSON.stringify(id)).join(' | ')};
export const extraMarks: Record<ExtraMarkId, { title: string; viewBox: string; html: string }> = {
${entries.join('\n')}
};
`);
console.log(`Wrote ${entries.length} marks to ${target}`);

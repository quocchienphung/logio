"""Extract the payment-methods "Explore countries" content templates into a TS data module.

The reference ships one <template data-js-target-list="PaymentMethodHubCountriesExplorer.contentTemplates"
data-js-country-code="XX"> per country; PaymentMethodHubCountriesExplorer clones the selected one into
PaymentMethodHubCountriesExplorer.contentEl. The page generator drops <template> elements, so the port reads
this module instead. Only payment-method logos (svg.PaymentLogo, brand marks that keep their colours) carry
colours; the script asserts that nothing else does.

Usage: python3 scripts/forensics/products/qa/pages-b-extract-country-templates.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SRC = ROOT / "docs/research/products/_raw/payment-methods.html"
OUT = ROOT / "src/components/sites/stripe-com-9ababc9a/v1/controllers/pg-payment-methods/data/countryContent.ts"

TEMPLATE_RE = re.compile(
    r'<template data-js-target-list="PaymentMethodHubCountriesExplorer.contentTemplates" '
    r'data-js-country-code="(\w+)">(.*?)</template>',
    re.S,
)


def squeeze(html: str) -> str:
    # class="\n  A\n  B\n" -> class="A B"
    html = re.sub(r'class="([^"]*)"', lambda m: 'class="%s"' % " ".join(m.group(1).split()), html)
    html = re.sub(r"<(\w+)\s+([^>]*?)\s*>", lambda m: "<%s %s>" % (m.group(1), " ".join(m.group(2).split())), html)
    html = re.sub(r">\s+<", "><", html)
    html = re.sub(r"\s+", " ", html)
    return html.strip()


def main() -> None:
    src = SRC.read_text(encoding="utf-8")
    out: dict[str, str] = {}
    for code, body in TEMPLATE_RE.findall(src):
        rest = re.sub(r'<svg class="PaymentLogo.*?</svg>', "", body, flags=re.S)
        assert not re.search(r"#[0-9a-fA-F]{3,8}\b|rgba?\(", rest), f"non-logo colour in {code}"
        assert "<img" not in body and "<script" not in body, f"unexpected element in {code}"
        out[code] = squeeze(body)
    assert len(out) >= 16, out.keys()
    lines = [
        "// Generated by scripts/forensics/products/qa/pages-b-extract-country-templates.py from",
        "// docs/research/products/_raw/payment-methods.html (the reference's PaymentMethodHubCountriesExplorer",
        "// content templates, which the page generator drops). Do not edit by hand.",
        "export const COUNTRY_CONTENT: Readonly<Record<string, string>> = {",
    ]
    for code, html in out.items():
        lines.append(f"  {code}: {json.dumps(html, ensure_ascii=False)},")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(out)} countries, {OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()

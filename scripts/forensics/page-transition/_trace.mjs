import fs from "node:fs";
import { chromium } from "playwright";
const [base = "http://localhost:3100", from = "/billing", label = "Payments", out = "trace.json"] = process.argv.slice(2);
const b = await chromium.launch({ channel: "chrome", headless: true });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
await p.goto(base + from, { waitUntil: "load" });
await p.waitForTimeout(1500);
const t = p.getByRole("button", { name: "Products" }).first();
const bb = await t.boundingBox();
await p.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2);
await p.waitForSelector(".navigation__content--products a", { state: "visible" });
const link = p.locator(".navigation__content--products a", { hasText: label }).first();
await link.hover();
await p.waitForTimeout(800);
await b.startTracing(p, { path: out, categories: ["devtools.timeline", "disabled-by-default-devtools.timeline", "blink", "cc", "viz", "gpu", "benchmark", "disabled-by-default-devtools.timeline.frame"] });
await link.click({ noWaitAfter: true });
await p.waitForTimeout(3000);
await b.stopTracing();
await b.close();

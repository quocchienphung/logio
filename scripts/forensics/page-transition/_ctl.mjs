import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome", headless: true });
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await p.goto("http://localhost:3100/billing", { waitUntil: "load" });
await p.waitForTimeout(1000);
const t = p.getByRole("button", { name: "Products" }).first();
const bb = await t.boundingBox();
await p.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2);
await p.waitForSelector(".navigation__content--products a", { state: "visible" });
const link = p.locator(".navigation__content--products a", { hasText: "Payments" }).first();
await link.hover();
await p.waitForTimeout(800);
await link.click({ noWaitAfter: true });
await p.waitForURL("**/payments");
await p.waitForTimeout(4000);
const m = await p.evaluate(() => performance.getEntriesByType("measure").filter((e) => e.name.startsWith("ctl ")).map((e) => [Math.round(e.startTime), +e.duration.toFixed(1), e.name]));
for (const r of m) if (r[1] > 4) console.log(r.join("  "));
console.log("count", m.length, "sum", m.reduce((s, r) => s + r[1], 0).toFixed(0));
await b.close();

import { chromium } from "playwright";
const base = "http://localhost:3000";
const b = await chromium.launch({ channel: "chrome", headless: true });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
const seen = [];
p.on("console", (m) => { if (["error", "warning"].includes(m.type())) { const l = m.location(); seen.push(`[${p.url().replace(base, "")}] ${m.type()} ${String(l.url).split("/").slice(-1)}:${l.lineNumber} :: ${m.text().slice(0, 1800)}`); } });
await p.goto(base + "/payments", { waitUntil: "load" });
await p.waitForTimeout(2500);
console.log("after /payments load:", seen.length);
const t = p.getByRole("button", { name: "Products" }).first();
const bb = await t.boundingBox();
await p.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2);
await p.waitForSelector(".navigation__content--products a", { state: "visible" });
await p.waitForTimeout(500);
await p.locator(".navigation__content--products a", { hasText: "Tax" }).first().click();
await p.waitForURL(base + "/tax");
await p.waitForTimeout(3000);
console.log("after menu -> /tax:", seen.length);
for (const s of seen) console.log(s, "\n");
await b.close();

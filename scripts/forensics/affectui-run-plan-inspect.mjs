import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';

const browser=await chromium.launch({channel:'chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
const page=await context.newPage();
const results=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
const settle=()=>page.waitForTimeout(450);
try {
  await page.goto(`${process.argv[2]||'http://localhost:3000'}/personalize?section=run`,{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Approve',exact:true}).waitFor({timeout:25000});
  assert.equal(await page.locator('.ui-pl__step').count(),5);
  results.push('Default five-step plan and approval pause');
  await page.locator('.ui-tc-group__head').first().click();
  await page.locator('.ui-tc__head').first().click();
  await page.locator('.ui-tc').first().getByRole('button',{name:'Copy arguments',exact:true}).click();
  assert.equal(JSON.parse(await page.evaluate(()=>navigator.clipboard.readText())).metric,'revenue');
  results.push('Group and card disclosures and real argument copy');
  await page.locator('.ui-tc').first().getByRole('button',{name:'Copy result',exact:true}).click();
  assert.equal(JSON.parse(await page.evaluate(()=>navigator.clipboard.readText())).total,4310000);
  results.push('Result JSON syntax rendering and real clipboard copy');
  await page.getByRole('button',{name:'Hide side panel',exact:true}).click();
  await page.getByRole('button',{name:'Waiting for your approval',exact:true}).click();
  assert.equal(await page.locator('#run-side-panel').isVisible(),true);
  results.push('Activity approval link restores hidden side panel');
  await page.getByRole('button',{name:'Stop run',exact:true}).click();
  await page.getByRole('button',{name:'Retry from here',exact:true}).click();
  await page.getByRole('button',{name:'Approve',exact:true}).waitFor();
  results.push('Stop and retry current step');
  await page.getByRole('button',{name:'Run options',exact:true}).click();
  await page.getByRole('menuitem',{name:'Edit plan',exact:true}).click();
  await page.locator('.ui-pl__step').first().focus();
  await page.locator('.ui-pl__step').first().press('Enter');
  await page.getByRole('textbox',{name:'Step name',exact:true}).fill('Revenue QA');
  await page.getByRole('textbox',{name:'Step name',exact:true}).press('Enter');
  assert.equal(await page.locator('.ui-pl__name').first().textContent(),'Revenue QA');
  results.push('Keyboard rename');
  await page.locator('.ui-pl__step').first().press('Alt+ArrowDown');
  assert.equal(await page.locator('.ui-pl__name').nth(1).textContent(),'Revenue QA');
  results.push('Keyboard reorder');
  await page.locator('.ui-pl__step').nth(1).press('Delete');
  await settle();
  assert.equal(await page.locator('.ui-pl__step').count(),4);
  results.push('Keyboard remove');
  await page.getByRole('textbox',{name:'Add a step at the end',exact:true}).fill('QA custom step');
  await page.getByRole('textbox',{name:'Add a step at the end',exact:true}).press('Enter');
  assert.equal(await page.locator('.ui-pl__step').count(),5);
  results.push('Add custom step');
  await settle();
  await page.locator('.ui-pl__grip').last().dragTo(page.locator('.ui-pl__step').first());
  assert.equal(await page.locator('.ui-pl__name').first().textContent(),'QA custom step');
  results.push('Pointer drag reorder across four positions');
  await page.getByRole('button',{name:'Run options',exact:true}).click();
  await page.getByRole('menuitem',{name:'Finish editing',exact:true}).click();
  assert.equal(await page.locator('.ui-pl').getAttribute('data-status'),'running');
  results.push('Finish editing returns live plan layout');
  assert.deepEqual(errors,[]);
  await fs.writeFile('docs/research/affectui-run/plan-activity-qa.json',JSON.stringify({results,errors},null,2));
  console.log(JSON.stringify({results,errors},null,2));
} finally { await browser.close(); }

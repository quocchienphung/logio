import fs from 'node:fs/promises';
import {chromium} from 'playwright';
const out='docs/research/invoice-credit';
const b=await chromium.launch({channel:'chrome'});
const p=await b.newPage({viewport:{width:1440,height:1100}});
await p.goto('https://www.affectui.com/blocks/invoice-credit',{waitUntil:'networkidle'});
await p.getByRole('button',{name:'Decline',exact:true}).click().catch(()=>{});
const root=p.locator('.ui-iv');
await root.screenshot({path:`${out}/source-invoice.png`});
await fs.writeFile(`${out}/source-dom.html`,await root.evaluate(e=>e.outerHTML));
await fs.writeFile(`${out}/source-styles.css`,await p.evaluate(()=>[...document.querySelectorAll('style')].map(s=>s.textContent).filter(s=>s.includes('.ui-iv')).join('\n')));
await fs.writeFile(`${out}/source-measurements.json`,JSON.stringify(await root.evaluate(r=>[r,...r.querySelectorAll('*')].map(e=>{const s=getComputedStyle(e),b=e.getBoundingClientRect();return {tag:e.tagName,class:e.className,text:e.textContent.slice(0,60),rect:{x:b.x,y:b.y,w:b.width,h:b.height},styles:Object.fromEntries(['fontFamily','fontSize','fontWeight','lineHeight','letterSpacing','color','backgroundColor','padding','gap','borderRadius','transform','transition','position','width','gridTemplateColumns'].map(k=>[k,s[k]]))}})),null,2));
await root.getByRole('button',{name:'Credit invoice',exact:true}).click();
await p.waitForTimeout(900);
await root.screenshot({path:`${out}/source-credit.png`});
await fs.writeFile(`${out}/source-credit-dom.html`,await root.evaluate(e=>e.outerHTML));
console.log('CREDIT',await root.innerText());
console.log('INPUTS',await root.locator('input').evaluateAll(es=>es.map(e=>({type:e.type,value:e.value,min:e.min,max:e.max,aria:e.getAttribute('aria-label'),html:e.outerHTML}))));
await root.getByRole('checkbox').first().click();
await p.waitForTimeout(600);console.log('UNCHECK',await root.innerText());
await root.locator('input').nth(1).fill('100');
await root.locator('input').nth(1).press('Enter');
await p.waitForTimeout(500);console.log('AMOUNT',await root.innerText());
await root.getByRole('button',{name:'Issue credit note',exact:true}).click();
await p.waitForTimeout(1000);console.log('ISSUED',await root.innerText());
await root.screenshot({path:`${out}/source-issued.png`});
await fs.writeFile(`${out}/source-issued-dom.html`,await root.evaluate(e=>e.outerHTML));
await p.setViewportSize({width:390,height:844});await p.waitForTimeout(600);await root.screenshot({path:`${out}/source-mobile-credit.png`});
await root.getByRole('tab',{name:'Invoice',exact:true}).click();await p.waitForTimeout(800);await root.screenshot({path:`${out}/source-mobile-invoice.png`});
await b.close();

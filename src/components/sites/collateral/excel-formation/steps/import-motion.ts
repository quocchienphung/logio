export function unfurlFrame(time: number, opening: boolean): UnfurlFrame {
  const samples = opening ? EXPAND_FRAMES : COLLAPSE_FRAMES;
  const next = samples.findIndex(frame => frame.t >= time);
  if (next === 0) return samples[0];
  if (next < 0) return samples[samples.length - 1];
  const a = samples[next - 1], b = samples[next], p = (time - a.t) / (b.t - a.t);
  const mix = (key: keyof UnfurlFrame) => a[key] + (b[key] - a[key]) * p;
  return { t: time, width: mix("width"), height: mix("height"), body: mix("body"), radius: mix("radius"), lift: mix("lift"), opacity: mix("opacity") };
}

"use client";

import { useCallback, useEffect, useId, useLayoutEffect, useRef, useState, useSyncExternalStore } from "react";
import type { KeyboardEvent, PointerEvent as ReactPointerEvent } from "react";
import {
  assignTask, busyMinutes, busyMinutesWith, clockLabel, defaultFormatCost, formatMinutes, initialsOf, leastBusyAgent,
  queueOf, queueTotals, unassignedOf,
  type DelegateAgent, type DelegateMode, type DelegateTask, type Suggestion, type ToolId,
} from "./delegate-model";
import { brandIcons, type BrandIconId } from "./brand-icons.generated";
import "../affectui-fonts.css";
import "./delegate-board.css";

export type DelegateBoardProps = {
  agents: readonly DelegateAgent[];
  tasks: readonly DelegateTask[];
  /** A drop, a keyboard pick or Auto. null means back to Unassigned. Without it the board moves tasks itself. */
  onAssign?: (taskId: string, agentId: string | null) => void;
  /** Auto hands every unassigned task to the least busy agent, about one a second; Manual waits for a drop. */
  mode?: DelegateMode;
  defaultMode?: DelegateMode;
  onModeChange?: (mode: DelegateMode) => void;
  /** A proposed hand-off: the agent lights up and previews its new time, the task is marked. */
  suggestion?: Suggestion | null;
  /** Formats every cost; swap in your currency or credits. Only used when an agent has a rate. */
  formatCost?: (amount: number) => string;
  /** The clock for the "Busy until" times. Defaults to the current time, refreshed every half minute. */
  now?: number;
  title?: string;
  /** Singular and plural for the people or agents that take the work. */
  agentLabel?: string;
  agentsLabel?: string;
  /** Chips shown in a queue before the rest collapse into a +N chip. */
  maxChips?: number;
  className?: string;
};

type Drag = { id: string; left: number; top: number; width: number; height: number; over: string | null };
type Pick = { id: string; index: number };

const PILE = "__pile";
const AUTO_FIRST_MS = 450;
const AUTO_STEP_MS = 1000;
const DRAG_SLOP = 4;
const reducedMotion = () => window.matchMedia("(prefers-reduced-motion: reduce)").matches;

/* The wall clock as an external store: the server renders no time at all, so hydration never disagrees. */
let clockNow = 0;
const clockListeners = new Set<() => void>();
let clockTimer: ReturnType<typeof setInterval> | undefined;
const subscribeClock = (listener: () => void) => {
  clockNow = Date.now();
  clockListeners.add(listener);
  clockTimer ??= setInterval(() => { clockNow = Date.now(); clockListeners.forEach(notify => notify()); }, 30_000);
  return () => {
    clockListeners.delete(listener);
    if (!clockListeners.size) { clearInterval(clockTimer); clockTimer = undefined; }
  };
};
const readClock = () => clockNow;
const serverClock = () => 0;

const Spark = () => <svg width="16" height="16" viewBox="0 0 16 16" aria-hidden="true"><path d="M8 1.6c.3 3.3 1.5 4.8 4.8 5.1-3.3.3-4.5 1.8-4.8 5.1-.3-3.3-1.5-4.8-4.8-5.1C6.5 6.4 7.7 4.9 8 1.6Z" fill="currentColor" /><path d="M12.6 10.6c.1 1.2.6 1.7 1.8 1.8-1.2.1-1.7.6-1.8 1.8-.1-1.2-.6-1.7-1.8-1.8 1.2-.1 1.7-.6 1.8-1.8Z" fill="currentColor" opacity=".55" /></svg>;
const Grip = () => <svg width="8" height="12" viewBox="0 0 8 12" aria-hidden="true" fill="currentColor">{[2, 6, 10].flatMap(y => [1.5, 6.5].map(x => <circle key={`${x}-${y}`} cx={x} cy={y} r="1" />))}</svg>;

const brandNames: Record<BrandIconId, string> = { anthropic: "Anthropic", openai: "OpenAI", gemini: "Gemini", notion: "Notion", github: "GitHub", slack: "Slack", figma: "Figma", hubspot: "HubSpot", stripe: "Stripe" };
/** A logo exactly as the public preview draws it. The markup is a constant generated by the export script, never user input. */
const Mark = ({ id }: { id: BrandIconId }) => {
  const icon = brandIcons[id];
  return <svg className="dgb__mark" data-mono={icon.mono ? "" : undefined} viewBox={icon.viewBox} fill={icon.fill ?? undefined} aria-hidden="true" dangerouslySetInnerHTML={{ __html: icon.html }} />;
};
const Tool = ({ id }: { id: ToolId }) => <span className="dgb__tool" title={brandNames[id]}><Mark id={id} /></span>;

const dropTarget = (x: number, y: number, root: HTMLElement | null) => {
  const hit = document.elementFromPoint(x, y)?.closest<HTMLElement>("[data-drop]");
  return hit && root?.contains(hit) ? hit.dataset.drop ?? null : null;
};

/**
 * Hand work to a team by dragging it onto them: each person previews the time they would be busy until, or switch to
 * Auto and every new task goes to whoever is free first. Drag a queued task to move it, or back to Unassigned. Keyboard:
 * Enter picks a task up, ↑ ↓ choose, Enter hands it over, Esc puts it back, 1–9 hand it over at once, 0 returns it.
 * The board fills its parent and scales as a unit (a 380px-wide design), so it keeps its proportions in a small frame.
 */
export function DelegateBoard({
  agents, tasks, onAssign, mode, defaultMode = "manual", onModeChange, suggestion = null, formatCost = defaultFormatCost, now,
  title = "Delegate", agentLabel = "agent", agentsLabel = "Agents", maxChips = 3, className,
}: DelegateBoardProps) {
  const root = useRef<HTMLDivElement>(null);
  const ids = useId();
  const [own, setOwn] = useState<readonly DelegateTask[]>(tasks);
  const [ownMode, setOwnMode] = useState<DelegateMode>(defaultMode);
  const [drag, setDrag] = useState<Drag | null>(null);
  const [pick, setPick] = useState<Pick | null>(null);
  const [note, setNote] = useState("");
  const [openMore, setOpenMore] = useState<string | null>(null);
  const list = onAssign ? tasks : own;
  const currentMode = mode ?? ownMode;
  const clock = useSyncExternalStore(subscribeClock, readClock, serverClock);
  const time = now ?? clock;
  const rects = useRef(new Map<string, { x: number; y: number }>());
  const focusAfter = useRef<string | null>(null);

  const listRef = useRef(list);
  const dragId = useRef<string | null>(null);

  const commit = useCallback((taskId: string, agentId: string | null) => {
    const task = listRef.current.find(item => item.id === taskId);
    if (!task || (task.agentId ?? null) === agentId) return false;
    const agent = agents.find(item => item.id === agentId);
    onAssign?.(taskId, agentId);
    if (!onAssign) setOwn(current => assignTask(current, taskId, agentId));
    setNote(agent ? `${task.title} handed to ${agent.name}` : `${task.title} is unassigned`);
    return true;
  }, [agents, onAssign]);

  const latest = useRef({ commit, agents });
  useLayoutEffect(() => { listRef.current = list; latest.current = { commit, agents }; });

  // Auto: one task a second goes to whoever is free first. The task under a pointer is left alone.
  useEffect(() => {
    if (currentMode !== "auto") return;
    let timer: ReturnType<typeof setTimeout>;
    const step = () => {
      const { commit: hand, agents: team } = latest.current;
      const next = unassignedOf(listRef.current).find(task => task.id !== dragId.current);
      const target = next && leastBusyAgent(team, listRef.current);
      if (next && target) hand(next.id, target);
      timer = setTimeout(step, AUTO_STEP_MS);
    };
    timer = setTimeout(step, AUTO_FIRST_MS);
    return () => clearTimeout(timer);
  }, [currentMode]);

  // A touch has no hover: tapping +N opens its list, and a tap anywhere else closes it.
  useEffect(() => {
    if (!openMore) return;
    const close = (event: PointerEvent) => { if (!(event.target as Element).closest?.(".dgb__more")) setOpenMore(null); };
    document.addEventListener("pointerdown", close, true);
    return () => document.removeEventListener("pointerdown", close, true);
  }, [openMore]);

  function setMode(next: DelegateMode) {
    onModeChange?.(next);
    if (mode === undefined) setOwnMode(next);
  }

  // FLIP: a task that moved glides from where it was (or from where it was dropped) to its new place.
  useLayoutEffect(() => {
    const board = root.current;
    if (!board) return;
    const origin = board.getBoundingClientRect();
    const next = new Map<string, { x: number; y: number }>();
    const animate = !reducedMotion();
    board.querySelectorAll<HTMLElement>("[data-flip]").forEach(element => {
      const id = element.dataset.flip as string;
      const box = element.getBoundingClientRect();
      const at = { x: box.left - origin.left, y: box.top - origin.top };
      next.set(id, at);
      const from = rects.current.get(id);
      if (!from || !animate) return;
      const dx = from.x - at.x;
      const dy = from.y - at.y;
      if (Math.abs(dx) + Math.abs(dy) > 1) element.animate([{ transform: `translate(${dx}px, ${dy}px)` }, { transform: "none" }], { duration: 420, easing: "cubic-bezier(0.32, 0.72, 0.24, 1)" });
    });
    rects.current = next;
    const focusId = focusAfter.current;
    if (focusId) {
      focusAfter.current = null;
      board.querySelector<HTMLElement>(`[data-flip="${CSS.escape(focusId)}"]`)?.focus({ preventScroll: true });
    }
  });

  function startDrag(event: ReactPointerEvent<HTMLElement>, task: DelegateTask) {
    if (event.button !== 0 || !event.isPrimary) return;
    const box = event.currentTarget.getBoundingClientRect();
    const start = { x: event.clientX, y: event.clientY };
    const pointerId = event.pointerId;
    let started = false;
    let over: string | null = null;
    const finish = (drop: boolean) => {
      window.removeEventListener("pointermove", move);
      window.removeEventListener("pointerup", up);
      window.removeEventListener("pointercancel", cancel);
      window.removeEventListener("keydown", escape, true);
      dragId.current = null;
      if (started) {
        const origin = root.current?.getBoundingClientRect();
        if (drop && over && origin) {
          // The ghost's place is where the hand-off starts gliding from.
          rects.current.set(task.id, { x: box.left + (last.x - start.x) - origin.left, y: box.top + (last.y - start.y) - origin.top });
          commit(task.id, over === PILE ? null : over);
        }
        setDrag(null);
      }
    };
    const last = { ...start };
    const move = (e: PointerEvent) => {
      if (e.pointerId !== pointerId) return;
      if (!started && Math.hypot(e.clientX - start.x, e.clientY - start.y) < DRAG_SLOP) return;
      started = true;
      dragId.current = task.id;
      last.x = e.clientX; last.y = e.clientY;
      over = dropTarget(e.clientX, e.clientY, root.current);
      const origin = root.current?.getBoundingClientRect();
      if (!origin) return;
      setPick(null);
      setDrag({ id: task.id, left: box.left + (e.clientX - start.x) - origin.left, top: box.top + (e.clientY - start.y) - origin.top, width: box.width, height: box.height, over });
    };
    const up = (e: PointerEvent) => { if (e.pointerId === pointerId) finish(true); };
    const cancel = (e: PointerEvent) => { if (e.pointerId === pointerId) finish(false); };
    const escape = (e: globalThis.KeyboardEvent) => { if (e.key === "Escape") { e.stopPropagation(); finish(false); } };
    window.addEventListener("pointermove", move);
    window.addEventListener("pointerup", up);
    window.addEventListener("pointercancel", cancel);
    window.addEventListener("keydown", escape, true);
  }

  function onTaskKey(event: KeyboardEvent<HTMLElement>, task: DelegateTask) {
    if (event.altKey || event.ctrlKey || event.metaKey) return;
    const picked = pick?.id === task.id ? pick : null;
    const handOver = (agentId: string | null) => {
      event.preventDefault();
      focusAfter.current = task.id;
      setPick(null);
      commit(task.id, agentId);
    };
    if (picked) {
      if (event.key === "ArrowDown" || event.key === "ArrowUp") {
        event.preventDefault();
        setPick({ id: task.id, index: (picked.index + (event.key === "ArrowDown" ? 1 : agents.length - 1)) % agents.length });
      } else if (event.key === "Enter" || event.key === " ") handOver(agents[picked.index].id);
      else if (event.key === "Escape") { event.preventDefault(); event.stopPropagation(); setPick(null); setNote(`${task.title} put back`); }
      else if (event.key === "Tab") setPick(null);
      else if (/^[0-9]$/.test(event.key)) handOver(event.key === "0" ? null : agents[Number(event.key) - 1]?.id ?? null);
      return;
    }
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      const at = agents.findIndex(agent => agent.id === task.agentId);
      setPick({ id: task.id, index: (at + 1) % agents.length });
      setNote(`${task.title} picked up. Choose with the arrow keys, Enter to hand over, Escape to put back.`);
    } else if (event.key === "0" && task.agentId) handOver(null);
    else if (/^[1-9]$/.test(event.key) && agents[Number(event.key) - 1]) handOver(agents[Number(event.key) - 1].id);
  }

  const waiting = unassignedOf(list);
  const movingId = drag?.id ?? pick?.id ?? suggestion?.taskId ?? null;
  const moving = list.find(task => task.id === movingId) ?? null;
  const targetId = drag ? (drag.over === PILE ? null : drag.over) : pick ? agents[pick.index]?.id ?? null : suggestion?.agentId ?? null;
  const totals = queueTotals(agents, list);
  const ghost = drag ? list.find(task => task.id === drag.id) : undefined;
  const help = `${ids}-help`;

  const taskCard = (task: DelegateTask) => <>
    <span className="dgb__grip"><Grip /></span>
    <span className="dgb__task-main">
      <span className="dgb__task-title">{task.title}</span>
      <span className="dgb__task-meta">
        {!!task.tools?.length && <span className="dgb__tools">{task.tools.map(tool => <Tool key={tool} id={tool} />)}</span>}
        <span>~{task.estimate} min</span>
      </span>
    </span>
  </>;

  return <div className="dgb-frame">
    <div
      ref={root}
      className={["dgb", className].filter(Boolean).join(" ")}
      data-dragging={drag ? "" : undefined}
      data-mode={currentMode}
    >
      <div className="dgb__bar">
        <span className="dgb__spark"><Spark /></span>
        <span className="dgb__title">{title}</span>
        <span className="dgb__hint">{pick ? "↑ ↓ to choose, Enter to hand over" : `Drag a task onto ${/^[aeiou]/i.test(agentLabel) ? "an" : "a"} ${agentLabel}`}</span>
        <button type="button" role="switch" aria-checked={currentMode === "auto"} className="dgb__auto" onClick={() => setMode(currentMode === "auto" ? "manual" : "auto")}>
          <span className="dgb__auto-label">Auto</span>
          <span className="dgb__switch"><span /></span>
        </button>
      </div>

      <div className="dgb__body">
        <section className="dgb__pile" aria-labelledby={`${ids}-pile`} data-drop={PILE} data-over={drag?.over === PILE ? "" : undefined}>
          <h4 className="dgb__head" id={`${ids}-pile`}>Unassigned <span className="dgb__count">{waiting.length}</span></h4>
          {waiting.length ? <ul className="dgb__tasks" aria-label="Unassigned tasks">
            {waiting.map(task => <li key={task.id} className="dgb__task-slot">
              <button
                type="button"
                className="dgb__task"
                data-flip={task.id}
                data-dragging={drag?.id === task.id ? "" : undefined}
                data-picked={pick?.id === task.id || suggestion?.taskId === task.id ? "" : undefined}
                aria-describedby={help}
                aria-pressed={pick?.id === task.id}
                onPointerDown={event => startDrag(event, task)}
                onKeyDown={event => onTaskKey(event, task)}
                onBlur={() => setPick(current => current?.id === task.id ? null : current)}
              >{taskCard(task)}</button>
            </li>)}
          </ul> : <p className="dgb__empty">All handed over</p>}
        </section>

        <section className="dgb__agents" aria-labelledby={`${ids}-agents`}>
          <h4 className="dgb__head" id={`${ids}-agents`}>
            {agentsLabel}
            <span className="dgb__spend" key={totals.priced ? totals.cost : totals.minutes}>{totals.priced ? formatCost(totals.cost) : formatMinutes(totals.minutes)} in queues</span>
          </h4>
          <ul className="dgb__roster">
            {agents.map((agent, index) => {
              const queue = queueOf(list, agent.id);
              const target = targetId === agent.id && !!moving && moving.agentId !== agent.id;
              const minutes = target ? busyMinutesWith(agent, list, moving) : busyMinutes(agent, queue);
              const kind = target ? "preview" : minutes > 0 ? "busy" : "free";
              const until = time ? clockLabel(time, minutes) : "--:--";
              const tagText = kind === "free" ? "Free" : kind === "preview" ? `+${moving?.estimate}m until ${until}` : `Busy until ${until}`;
              const price = target && agent.rate !== undefined ? `+${formatCost(agent.rate * moving.estimate)}` : null;
              const shown = queue.slice(0, maxChips);
              const rest = queue.slice(maxChips);
              return <li key={agent.id} className="dgb__agent" data-drop={agent.id} data-target={targetId === agent.id && (!!moving || !!drag) ? "" : undefined}>
                <span className="dgb__avatar" data-logo={agent.logo ? "" : undefined}>{agent.logo ? <Mark id={agent.logo} /> : initialsOf(agent)}</span>
                <span className="dgb__who">
                  <span className="dgb__name-line">
                    <span className="dgb__name">{agent.name}</span>
                    {index < 9 && <span className="dgb__key" aria-hidden="true">{index + 1}</span>}
                  </span>
                  {(agent.model || agent.rate !== undefined) && <span className="dgb__model">{agent.model}{agent.rate !== undefined && <span className="dgb__rate">{formatCost(agent.rate)}/min</span>}</span>}
                </span>
                <span className="dgb__load">
                  {price && <span className="dgb__price" key={price}>{price}</span>}
                  <span className="dgb__tag" data-kind={kind} key={`${kind}-${tagText}`}>{tagText}</span>
                </span>
                {queue.length > 0 && <ul className="dgb__queue" aria-label={`${agent.name} queue`}>
                  {shown.map((task, position) => <li key={task.id} className="dgb__chip-slot">
                    <button
                      type="button"
                      className="dgb__chip"
                      data-flip={task.id}
                      data-running={position === 0 ? "" : undefined}
                      data-dragging={drag?.id === task.id ? "" : undefined}
                      data-picked={pick?.id === task.id ? "" : undefined}
                      aria-describedby={help}
                      aria-pressed={pick?.id === task.id}
                      title={task.title}
                      onPointerDown={event => startDrag(event, task)}
                      onKeyDown={event => onTaskKey(event, task)}
                      onBlur={() => setPick(current => current?.id === task.id ? null : current)}
                    >
                      {position > 0 && task.tools?.[0] && <Tool id={task.tools[0]} />}
                      {position === 0 && <svg className="dgb__spin" width="12" height="12" viewBox="0 0 12 12" aria-hidden="true" fill="none" stroke="currentColor" strokeWidth="1.4" strokeLinecap="round"><circle cx="6" cy="6" r="4.2" opacity=".25" /><path d="M6 1.8a4.2 4.2 0 0 1 4.2 4.2" /></svg>}
                      <span className="dgb__chip-title">{task.title}</span>
                    </button>
                  </li>)}
                  {rest.length > 0 && <li className="dgb__chip-slot dgb__more" data-open={openMore === agent.id ? "" : undefined}>
                    <button type="button" className="dgb__chip dgb__chip--more" aria-expanded={openMore === agent.id} onClick={() => setOpenMore(current => current === agent.id ? null : agent.id)} onKeyDown={event => { if (event.key === "Escape") setOpenMore(null); }} aria-label={`${rest.length} more tasks in ${agent.name}'s queue`}>+{rest.length}</button>
                    <span className="dgb__tip" role="tooltip"><ul className="dgb__tip-list">
                      {rest.map(task => <li key={task.id}>{task.tools?.map(tool => <Tool key={tool} id={tool} />)}<span>{task.title}</span><span className="dgb__tip-min">~{task.estimate} min</span></li>)}
                    </ul></span>
                  </li>}
                </ul>}
              </li>;
            })}
          </ul>
        </section>
      </div>

      <p className="dgb__sr" id={help}>Drag onto {/^[aeiou]/i.test(agentLabel) ? "an" : "a"} {agentLabel}, or press Enter, choose with the arrow keys and press Enter again. Number keys hand it over at once.</p>
      <div className="dgb__sr" role="status" aria-live="polite">{note}</div>

      {drag && ghost && <div
        className="dgb__ghost"
        aria-hidden="true"
        style={{ left: drag.left, top: drag.top, width: drag.width, minHeight: drag.height }}
      >{taskCard(ghost)}</div>}
    </div>
  </div>;
}
